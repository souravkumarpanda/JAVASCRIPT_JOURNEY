// AND (&&) operator
console.log(true && true); // true
console.log(true && false); // false
console.log(false && false); // false
let x = 5;
let y = 10;
console.log(x < 10 && y > 5); // true (both conditions are true)

// OR (||) operator
console.log(true || true); // true
console.log(true || false); // true
console.log(false || false); // false
let a = 5;
let b = 10;
console.log(a < 10 || b > 15); // true (one condition is true)

// NOT (!) operator
console.log(!true); // false
console.log(!false); // true
let isRaining = false;
console.log(!isRaining); // true (negates the value of isRaining)
