let x = 5;
let y = 10;
let z = x + y; // Addition
console.log(z); // Output: 15

let d = y - x; // Subtraction
console.log(d); // Output: 5

let m = x * y; // Multiplication
console.log(m); // Output: 50

let q = y / x; // Division
console.log(q); // Output: 2

let r = y % x; // Modulus
console.log(r); // Output: 0

let p = x ** 2; // Exponentiation
console.log(p); // Output: 25
